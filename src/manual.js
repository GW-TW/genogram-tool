  // 極簡 Markdown → HTML：先整段跳脫，再套格式，所以內容永遠不會變成 HTML 標籤
  function render(md) {
    const esc = GT.render.esc;
    const inline = (s) => esc(s).replace(/\*\*(.+?)\*\*/g, '<b>$1</b>').replace(/\[\[(.+?)\]\]/g, '<kbd>$1</kbd>');
    const out = [];
    let list = null, para = [];
    const flushPara = () => { if (para.length) { out.push('<p>' + para.map(inline).join('<br>') + '</p>'); para = []; } };
    const flushList = () => {
      if (!list) return;
      out.push('<' + list.tag + '>' + list.items.map(i => '<li>' + inline(i) + '</li>').join('') + '</' + list.tag + '>');
      list = null;
    };
    const item = (tag, text) => { flushPara(); if (!list || list.tag !== tag) { flushList(); list = { tag, items: [] }; } list.items.push(text); };
    for (const raw of String(md).split('\n')) {
      const line = raw.trim();
      let m;
      if (!line) { flushPara(); flushList(); continue; }
      if ((m = line.match(/^##\s+(.*)$/))) { flushPara(); flushList(); out.push('<h3>' + inline(m[1]) + '</h3>'); continue; }
      if ((m = line.match(/^>\s?(.*)$/))) { flushPara(); flushList(); out.push('<div class="tip">' + inline(m[1]) + '</div>'); continue; }
      if ((m = line.match(/^-\s+(.*)$/))) { item('ul', m[1]); continue; }
      if ((m = line.match(/^\d+\.\s+(.*)$/))) { item('ol', m[1]); continue; }
      flushList(); para.push(line);
    }
    flushPara(); flushList();
    return out.join('');
  }

